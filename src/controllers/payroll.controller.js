const prisma = require('../prisma');

/**
 * GET /api/payroll/generate?month=YYYY-MM
 * Calculates monthly payroll for all active staff:
 * - Base Salary (from User record)
 * - Total Commissions Earned (Sum of commission from completed Job Cards in the requested month)
 * - Total Payout = Base Salary + Commissions Earned
 */
async function generatePayrollHandler(req, res, next) {
  try {
    const monthQuery = req.query.month || new Date().toISOString().slice(0, 7); // e.g. "2026-10"
    const [yearStr, monthStr] = monthQuery.split('-');
    const year = parseInt(yearStr, 10);
    const monthIndex = parseInt(monthStr, 10) - 1; // 0-indexed in JS Date

    if (isNaN(year) || isNaN(monthIndex) || monthIndex < 0 || monthIndex > 11) {
      return res.status(400).json({
        status: 'error',
        message: 'Invalid month parameter. Format must be YYYY-MM (e.g. 2026-10).',
      });
    }

    const startOfMonth = new Date(Date.UTC(year, monthIndex, 1, 0, 0, 0, 0));
    const endOfMonth = new Date(Date.UTC(year, monthIndex + 1, 0, 23, 59, 59, 999));

    // Fetch active users (Workers, Cashiers, Admins)
    const users = await prisma.user.findMany({
      where: { is_active: true },
      orderBy: [{ role: 'asc' }, { name: 'asc' }],
    });

    // Fetch completed job cards in the requested month with services
    const completedJobCards = await prisma.jobCard.findMany({
      where: {
        status: 'Completed',
        updated_at: {
          gte: startOfMonth,
          lte: endOfMonth,
        },
        worker_id: { not: null },
      },
      include: {
        services: true,
      },
    });

    let totalPayrollExpense = 0;
    let totalCommissionsDistributed = 0;
    let totalBaseSalaries = 0;

    const staffPayroll = users.map((user) => {
      const baseSalary = parseFloat(user.base_salary || 0);
      const commissionRate = parseFloat(user.commission_rate || 0);

      // Find job cards completed by this worker
      const userJobs = completedJobCards.filter((job) => job.worker_id === user.id);

      // Total revenue generated by worker
      let workerRevenue = 0;
      for (const job of userJobs) {
        const jobRevenue = job.services.reduce((acc, s) => acc + parseFloat(s.price_charged || 0), 0);
        workerRevenue += jobRevenue;
      }

      // Commission calculation: (Revenue * Commission Rate) / 100
      const commissionsEarned = parseFloat(((workerRevenue * commissionRate) / 100).toFixed(2));
      const totalPayout = parseFloat((baseSalary + commissionsEarned).toFixed(2));

      totalBaseSalaries += baseSalary;
      totalCommissionsDistributed += commissionsEarned;
      totalPayrollExpense += totalPayout;

      return {
        user_id: user.id,
        name: user.name,
        role: user.role,
        base_salary: baseSalary,
        commission_rate: commissionRate,
        completed_jobs_count: userJobs.length,
        total_revenue_generated: parseFloat(workerRevenue.toFixed(2)),
        commissions_earned: commissionsEarned,
        total_payout: totalPayout,
      };
    });

    return res.status(200).json({
      status: 'success',
      month: monthQuery,
      period: {
        from: startOfMonth.toISOString(),
        to: endOfMonth.toISOString(),
      },
      summary: {
        staff_count: staffPayroll.length,
        total_base_salaries: parseFloat(totalBaseSalaries.toFixed(2)),
        total_commissions: parseFloat(totalCommissionsDistributed.toFixed(2)),
        total_payroll_expense: parseFloat(totalPayrollExpense.toFixed(2)),
      },
      payroll: staffPayroll,
    });
  } catch (error) {
    next(error);
  }
}

/**
 * PATCH /api/payroll/users/:id/salary
 * Updates user base salary and commission rate
 */
async function updateStaffSalaryHandler(req, res, next) {
  try {
    const { id } = req.params;
    const { base_salary, commission_rate, flat_commission } = req.body;

    const data = {};
    if (base_salary !== undefined) data.base_salary = parseFloat(base_salary) || 0;
    if (commission_rate !== undefined) data.commission_rate = parseFloat(commission_rate) || 0;
    if (flat_commission !== undefined) data.flat_commission = parseFloat(flat_commission) || 0;

    const updated = await prisma.user.update({
      where: { id },
      data,
    });

    return res.status(200).json({
      status: 'success',
      message: `Staff member ${updated.name} compensation updated successfully.`,
      data: updated,
    });
  } catch (error) {
    next(error);
  }
}

module.exports = {
  generatePayrollHandler,
  updateStaffSalaryHandler,
};
